namespace Catalyst.Tests.Services;

/// <summary>
/// Generator behaviour that a snapshot cannot express: counters, warnings and the version fallback.
/// The shape of the generated code is asserted by the snapshots (SnapshotTests).
/// </summary>
public class TypeScriptGeneratorTests
{
    [Fact]
    public void Generate_SkipsConfiguredPaths_AndReportsCount()
    {
        TypeScriptGenerator generator = SpecLoader.CreateGenerator(SpecLoader.Load("edge-cases"), skipPaths: ["/internal/"]);

        string code = generator.Generate();

        Assert.Equal(1, generator.SkippedPathCount);
        Assert.DoesNotContain("internalHealth", code);
    }

    [Fact]
    public void Generate_DoesNotSkipPaths_WhenNoSkipListProvided()
    {
        TypeScriptGenerator generator = SpecLoader.CreateGenerator(SpecLoader.Load("edge-cases"));

        string code = generator.Generate();

        Assert.Equal(0, generator.SkippedPathCount);
        Assert.Contains("internalHealth", code);
    }

    [Fact]
    public void Generate_Header_FallsBackToAssemblyVersion()
    {
        TypeScriptGenerator generator = new(SpecLoader.Load("minimal"), null);

        string code = generator.Generate();

        Assert.Matches(@"//  Generated by Catalyst \d+\.\d+\.\d+\s", code);
    }

    [Fact]
    public void Generate_Warnings_ReportDuplicateMethodNames()
    {
        // /users/{user_id} and /users/{userId} both PascalCase to "GetUsersUserId"
        OpenApiDocument document = SpecLoader.Parse("""
            {
                "openapi": "3.0.3",
                "info": { "title": "WarnTest", "version": "1.0" },
                "paths": {
                    "/users/{user_id}": {
                        "get": {
                            "parameters": [{ "name": "user_id", "in": "path", "required": true, "schema": { "type": "string" } }],
                            "responses": { "200": { "description": "OK" } }
                        }
                    },
                    "/users/{userId}": {
                        "get": {
                            "parameters": [{ "name": "userId", "in": "path", "required": true, "schema": { "type": "string" } }],
                            "responses": { "200": { "description": "OK" } }
                        }
                    }
                }
            }
            """);
        TypeScriptGenerator generator = new(document, "WarnTest");

        generator.Generate();

        Issue warning = Assert.Single(generator.Warnings);
        Assert.Equal(IssueCodes.DuplicateMethodName, warning.Code);
        Assert.Contains("Duplicate method name", warning.Message);
    }

    [Fact]
    public void Generate_KeepsMethodNamesUnique_AfterLowerCasing()
    {
        // "GetUser" and "getUser" are one name; "User" collides with the stripped form; all stay distinct camelCase keys.
        OpenApiDocument document = SpecLoader.Parse("""
            {
                "openapi": "3.0.3",
                "info": { "title": "Names", "version": "1.0" },
                "paths": {
                    "/a": { "get": { "operationId": "GetUser", "responses": { "200": { "description": "OK" } } } },
                    "/b": { "get": { "operationId": "getUser", "responses": { "200": { "description": "OK" } } } },
                    "/c": { "get": { "operationId": "User", "responses": { "200": { "description": "OK" } } } }
                }
            }
            """);
        TypeScriptGenerator generator = new(document, "Names");

        generator.Generate();

        List<string> methods = generator.Model.Operations.Select(o => o.MethodName).ToList();
        Assert.Equal(3, methods.Distinct().Count());
        Assert.All(methods, name => Assert.True(char.IsLower(name[0]), name));
    }

    [Fact]
    public void Generate_Warnings_ReportPathParameterMismatches()
    {
        TypeScriptGenerator generator = SpecLoader.CreateGenerator(SpecLoader.Load("edge-cases"));

        generator.Generate();

        Assert.Contains(generator.Warnings, w => w.Code == IssueCodes.PathParameterMismatch && w.Message.Contains("\"lineNo\"") && w.Message.Contains("not declared"));
        Assert.Contains(generator.Warnings, w => w.Code == IssueCodes.PathParameterMismatch && w.Message.Contains("\"ghost\"") && w.Message.Contains("does not appear"));
        Assert.Equal(2, generator.Warnings.Count);
    }
}
